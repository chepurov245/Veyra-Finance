from datetime import datetime


CURRENT_TIME_WORDS = {
    "сейчас",
    "текущий",
    "текущая",
    "текущее",
    "текущие",
    "сегодня",
    "на сегодня",
    "сегодняшний",
    "сегодняшняя",
    "этот месяц",
    "текущий месяц",
    "последний",
    "последние",
    "latest",
    "current",
    "today",
}


class QueryEnricher:

    def enrich(self, query: str) -> str:
        query = query.strip()

        if not query:
            return query

        lowered = query.lower()

        requires_freshness = any(
            phrase in lowered
            for phrase in CURRENT_TIME_WORDS
        )

        if not requires_freshness:
            return query

        now = datetime.now()

        return (
            f"{query}\n\n"
            "ИНСТРУКЦИИ ПО АКТУАЛЬНОСТИ:\n"
            f"- Сегодня: {now:%Y-%m-%d}.\n"
            f"- Текущий год: {now:%Y}.\n"
            "- Запрос относится к текущему состоянию "
            "показателя.\n"
            "- Ищи самые свежие фактические данные, "
            "доступные на текущую дату.\n"
            "- В первую очередь используй официальные "
            "источники: Росстат, Банк России, "
            "государственные органы и официальные "
            "статистические публикации.\n"
            "- Не используй данные 2025 года или более "
            "старые данные, если существуют более новые "
            "данные за 2026 год.\n"
            "- Не заменяй текущий показатель прогнозом.\n"
            "- Не смешивай исторические значения с "
            "текущим показателем.\n"
            "- Для каждого числового значения учитывай "
            "дату или период, к которому оно относится.\n"
            "- Если точное значение за текущую дату "
            "ещё официально не опубликовано, укажи "
            "последнее доступное значение и его дату.\n"
        )
